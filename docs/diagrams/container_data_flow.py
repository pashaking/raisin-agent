def anchor(name, side, f=0.5):
    x, y, w, h, *_ = B[name]
    return {"l": (x, y + h*f), "r": (x + w, y + h*f), "t": (x + w*f, y), "b": (x + w*f, y + h)}[side]

def pt(p): return f"{p[0]:.1f} {p[1]:.1f}"

def curve_ctrl(a, b):
    (x1,y1),(x2,y2) = a,b
    dx, dy = x2-x1, y2-y1
    if abs(dx) >= abs(dy):
        return (x1 + dx*0.5, y1), (x2 - dx*0.5, y2)
    return (x1, y1 + dy*0.5), (x2, y2 - dy*0.5)

def offset_pts(pts, d):
    """Offset a polyline by d along the left normal of travel (consecutive segments meet at line intersections)."""
    segs = []
    for a, b in zip(pts, pts[1:]):
        dx, dy = b[0]-a[0], b[1]-a[1]; L = (dx*dx+dy*dy)**.5 or 1
        nx, ny = -dy/L*d, dx/L*d
        segs.append(((a[0]+nx, a[1]+ny), (b[0]+nx, b[1]+ny)))
    out = [segs[0][0]]
    for (a1,b1),(a2,b2) in zip(segs, segs[1:]):
        x1,y1,x2,y2 = *a1,*b1; x3,y3,x4,y4 = *a2,*b2
        den = (x1-x2)*(y3-y4)-(y1-y2)*(x3-x4)
        if abs(den) < 1e-6: out.append(b1); continue
        t = ((x1-x3)*(y3-y4)-(y1-y3)*(x3-x4))/den
        out.append((x1+t*(x2-x1), y1+t*(y2-y1)))
    out.append(segs[-1][1])
    return out

def offset_curve(pts, d):
    """Offset a 2-point curve by shifting both ends along the chord normal (good enough at 4px)."""
    (x1,y1),(x2,y2) = pts[0], pts[-1]
    dx, dy = x2-x1, y2-y1; L = (dx*dx+dy*dy)**.5 or 1
    nx, ny = -dy/L*d, dx/L*d
    return [(x1+nx, y1+ny), (x2+nx, y2+ny)]

def shift(pts, route, d):
    return offset_curve(pts, d) if route == "c" else offset_pts(pts, d)

def path_d(pts, route):
    if route == "c":
        c1, c2 = curve_ctrl(pts[0], pts[-1])
        return f"M {pt(pts[0])} C {pt(c1)} {pt(c2)} {pt(pts[-1])}"
    return "M " + " L ".join(pt(p) for p in pts)

def point_at(pts, route, t):
    if route == "c":
        (x1,y1),(x2,y2) = pts[0], pts[-1]
        c1, c2 = curve_ctrl(pts[0], pts[-1]); u = 1-t
        return (u**3*x1 + 3*u*u*t*c1[0] + 3*u*t*t*c2[0] + t**3*x2,
                u**3*y1 + 3*u*u*t*c1[1] + 3*u*t*t*c2[1] + t**3*y2)
    # polyline: walk by length
    segs = [(pts[i], pts[i+1]) for i in range(len(pts)-1)]
    L = [((b[0]-a[0])**2 + (b[1]-a[1])**2)**.5 for a,b in segs]
    target = t*sum(L); acc = 0
    for (a,b),l in zip(segs, L):
        if acc + l >= target or (a,b) == segs[-1]:
            k = (target-acc)/l if l else 0
            return (a[0]+(b[0]-a[0])*k, a[1]+(b[1]-a[1])*k)
        acc += l
    return pts[-1]

